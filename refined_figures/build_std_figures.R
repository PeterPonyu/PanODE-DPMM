read_npy_array <- function(path) {
  con <- file(path, "rb"); on.exit(close(con))
  magic <- readBin(con, "raw", 6)
  if (!identical(as.integer(magic), as.integer(charToRaw("\x93NUMPY")))) stop("Not an NPY file: ", path)
  version <- readBin(con, "integer", 2, size = 1, signed = FALSE)
  hlen <- if (version[1] <= 1) readBin(con, "integer", 1, size = 2, endian = "little", signed = FALSE) else readBin(con, "integer", 1, size = 4, endian = "little", signed = FALSE)
  header <- rawToChar(readBin(con, "raw", hlen))
  descr <- sub(".*'descr': '([^']+)'.*", "\\1", header)
  shape_txt <- sub(".*'shape': \\(([^)]*)\\).*", "\\1", header)
  shape <- as.integer(gsub("[^0-9,]", "", strsplit(shape_txt, ",")[[1]]))
  shape <- shape[!is.na(shape)]
  n <- prod(shape)
  if (descr == "<f4") values <- readBin(con, "numeric", n, size = 4, endian = "little")
  else if (descr == "<f8") values <- readBin(con, "numeric", n, size = 8, endian = "little")
  else if (descr == "<i4") values <- readBin(con, "integer", n, size = 4, endian = "little", signed = TRUE)
  else stop("Unsupported NPY dtype ", descr, " in ", path)
  if (length(shape) == 2) matrix(values, nrow = shape[1], ncol = shape[2], byrow = TRUE) else values
}

read_npz_member <- function(npz_path, member) {
  td <- tempfile("npz_"); dir.create(td)
  on.exit(unlink(td, recursive = TRUE), add = TRUE)
  utils::unzip(npz_path, files = member, exdir = td)
  read_npy_array(file.path(td, member))
}

