parse_table_number <- function(path, model, col_index) {
  lines <- readLines(path, warn = FALSE)
  row <- lines[startsWith(trimws(lines), model)][1]
  if (is.na(row)) stop("Could not find row for ", model, " in ", path)
  row <- gsub("\\\\textbf\\{|\\}", "", row)
  row <- gsub("\\\\\\\\", "", row)
  parts <- strsplit(row, "&", fixed = TRUE)[[1]]
  as.numeric(gsub("[^0-9.]", "", parts[col_index]))
}

