panel_base <- function(title, tag) {
  ggplot() +
    labs(title = title, tag = tag) +
    theme(plot.title = element_text(face = "bold"), plot.tag = element_text(face = "bold"))
}

text_panel <- function(title, tag, lines, color = "#2F4B7C") {
  y <- seq(0.78, 0.22, length.out = length(lines))
  df <- data.frame(x = 0.08, y = y, label = lines)
  panel_base(title, tag) +
    annotate("rect", xmin = 0.02, xmax = 0.98, ymin = 0.06, ymax = 0.92,
             fill = FILL_GRAY, colour = color, linewidth = 0.45) +
    geom_text(data = df, aes(x, y, label = label), hjust = 0, vjust = 1,
              size = 2.7, lineheight = 1.05, colour = INK) +
    coord_cartesian(xlim = c(0, 1), ylim = c(0, 1), expand = FALSE) +
    theme_void(base_size = STD_BASE_SIZE) +
    theme(plot.title = element_text(size = STD_BASE_SIZE + 1, face = "bold", hjust = 0),
          plot.tag = element_text(size = STD_BASE_SIZE + 2, face = "bold"),
          plot.margin = margin(2, 2, 2, 2))
}

bar_panel <- function(df, x, y, fill = NULL, title, tag, ylabel = "", xlabel = NULL,
                      rotate = 25, limits = NULL) {
  aes_base <- aes(x = .data[[x]], y = .data[[y]])
  p <- ggplot(df, aes_base) + labs(title = title, tag = tag, x = xlabel, y = ylabel)
  if (!is.null(fill)) {
    p <- p + geom_col(aes(fill = .data[[fill]]), width = 0.68, colour = "white", linewidth = 0.25) +
      scale_fill_manual(values = COLORS, guide = guide_legend(title = NULL))
  } else {
    p <- p + geom_col(width = 0.68, fill = "#4E79A7", colour = "white", linewidth = 0.25)
  }
  if (!is.null(limits)) p <- p + coord_cartesian(ylim = limits)
  p + std_theme() +
    theme(plot.title = element_text(face = "bold", hjust = 0),
          axis.text.x = element_text(angle = rotate, hjust = 1),
          legend.position = if (is.null(fill)) "none" else "top",
          panel.grid.major.x = element_blank(), panel.grid.minor = element_blank())
}

save_panel <- function(p, fig, tag, slug, w = 2.35, h = 1.70) {
  f <- file.path(PANEL_OUT, sprintf("F%02d%s_%s.tex", fig, tag, slug))
  fitted <- save_tikz_std(p, f, plot_w_in = w, plot_h_in = h, sanitize = TRUE)
  data.frame(figure = sprintf("F%02d", fig), panel = tag, file = f,
             plot_w_in = w, plot_h_in = h, canvas_w_in = fitted$w_in,
             canvas_h_in = fitted$h_in, stringsAsFactors = FALSE)
}

write_wrapper <- function(fig, slug, composed_file, source_note) {
  base <- sprintf("F%02d_%s", fig, slug)
  wrapper <- file.path(OUT, paste0(base, ".tex"))
  rel <- file.path("figures", "submission", "tikz", basename(composed_file))
  body <- sprintf("%% Auto-generated by refined_figures/build_std_figures.R\n%% Source: %s\n\\resizebox{\\textwidth}{!}{%%\n\\input{%s}%%\n}\n", source_note, rel)
  writeLines(body, wrapper)
  wrapper
}

save_figure <- function(panels, fig, slug, source_note, ncol = 2, w = 2.35, h = 1.70) {
  f <- file.path(PANEL_OUT, sprintf("F%02d_%s_composed.tex", fig, slug))
  composed <- save_tikz_composed(panels, f, ncol = ncol, plot_w_in = w, plot_h_in = h,
                                 sanitize = TRUE)
  write_wrapper(fig, slug, f, source_note)
  panel_tags <- LETTERS[seq_along(panels)]
  data.frame(figure = sprintf("F%02d", fig), panel = panel_tags, file = f,
             plot_w_in = w, plot_h_in = h,
             canvas_w_in = vapply(composed$fits, function(x) x$w_in, numeric(1)),
             canvas_h_in = vapply(composed$fits, function(x) x$h_in, numeric(1)),
             composed_w_in = composed$w_in, composed_h_in = composed$h_in,
             stringsAsFactors = FALSE)
}

